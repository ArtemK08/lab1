# 1. Введення даних з перевіркою на коректність
while True:
    try:
        distance = float(input("Введіть пройдену відстань (км): "))
        fuel = float(input("Введіть кількість витраченого палива (л): "))
        
        # Перевірка на логічні помилки у введених даних
        if distance <= 0 or fuel < 0:
            raise ValueError("Відстань повинна бути більшою за нуль, а витрачене паливо — невід'ємним числом.")
        break
    except ValueError as e:
        print(f"Помилка: {e} Спробуйте ще раз.")

# 2. Обчислення витрат палива на 100 км
consumption_per_100 = (fuel / distance) * 100

# 3. Виведення результатів
print("\nРезультати обчислень:")
print(f"Пройдена відстань: {distance:.2f} км")
print(f"Витрачено палива: {fuel:.2f} л")
print(f"Витрати палива на 100 км: {consumption_per_100:.2f} л/100км")

# 4. Додаткова функціональність (оцінка ефективності)
if consumption_per_100 < 6:
    print("Економічний автомобіль!")
elif 6 <= consumption_per_100 <= 10:
    print("Середній показник витрати палива.")
else:
    print("Підвищена витрата палива.")

